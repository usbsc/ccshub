#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";

const TEAMS_PATH = path.join(process.cwd(), "src/app/data/teams.ts");
const OUT_PATH = path.join(process.cwd(), "src/app/data/teams.wikipedia.generated.ts");

function parseTeams(tsText) {
  const out = [];
  const re = /\{\s*id:\s*"([^"]+)"[\s\S]*?name:\s*"([^"]+)"[\s\S]*?mascot:\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(tsText))) out.push({ id: m[1], name: m[2], mascot: m[3] });
  return out;
}

function buildSearchTerms(team) {
  return [team.name, team.mascot, `${team.name} High School`].filter(Boolean).join(" ");
}

async function fetchWikipediaLogo(team) {
  const search = new URL("https://en.wikipedia.org/w/api.php");
  search.searchParams.set("action", "query");
  search.searchParams.set("format", "json");
  search.searchParams.set("origin", "*");
  search.searchParams.set("generator", "search");
  search.searchParams.set("gsrsearch", buildSearchTerms(team));
  search.searchParams.set("gsrlimit", "5");
  search.searchParams.set("prop", "pageimages");
  search.searchParams.set("piprop", "original");

  const res = await fetch(search);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const json = await res.json();
  const pages = json?.query?.pages ? Object.values(json.query.pages) : [];
  for (const page of pages) {
    const source = page?.original?.source;
    if (typeof source === "string" && source.startsWith("http")) return source;
  }
  return null;
}

async function main() {
  const tsText = await fs.readFile(TEAMS_PATH, "utf8");
  const teams = parseTeams(tsText);
  const out = {};

  for (const team of teams) {
    try {
      const logo = await fetchWikipediaLogo(team);
      if (logo) out[team.id] = logo;
      console.log(`${team.id}: ${logo ? "ok" : "missing"}`);
    } catch {
      console.log(`${team.id}: error`);
    }
  }

  const file =
    `// Auto-generated by scripts/update-wikipedia-team-logos.mjs\n` +
    `export const wikipediaTeamLogos: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
  await fs.writeFile(OUT_PATH, file, "utf8");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
